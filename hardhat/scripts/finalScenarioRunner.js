const { ethers } = require('hardhat');
const fs = require('fs');

async function runScenario(file, tokenConfig, report) {
  console.log(`\n📂 Running scenario from ${file}...`);
  const scenario = JSON.parse(fs.readFileSync(file, 'utf8'));

  const {
    contractAddress,
    primaryWallet,
    fallbackWallet,
    overlayTier,
    expectedRate,
    maxOracleDelay,
    assets,
    dryRunFirst
  } = scenario;

  const executor = await ethers.getContractAt('SovereignFlashLoanExecutor', contractAddress);

  // --- Governance setup ---
  let governanceStatus = 'success';
  try {
    await (await executor.updateProfitWallet(primaryWallet)).wait();
    await (await executor.setFallbackWallet(fallbackWallet)).wait();
    await (await executor.setOverlayTier(overlayTier)).wait();
    await (await executor.setExpectedRate(expectedRate)).wait();
    await (await executor.setMaxOracleDelay(maxOracleDelay)).wait();
    console.log('✅ Governance parameters set.');
  } catch (e) {
    governanceStatus = `failed: ${e.message}`;
    console.log('❌ Governance setup failed:', e.message);
  }

  // --- Batch asset execution ---
  const assetResults = [];
  for (const asset of assets) {
    console.log(`\n=== Asset: ${asset} ===`);
    const decimals = tokenConfig[asset]?.decimals || 18;
    const flashLoanAmount = ethers.parseUnits('1000', decimals);

    let status = 'dry-run';
    if (!dryRunFirst) {
      try {
        await (await executor.initiateFlashLoan(flashLoanAmount)).wait();
        console.log(`✅ Flash loan of 1000 ${asset} executed successfully`);
        status = 'executed';
      } catch (e) {
        console.log(`❌ Flash loan for ${asset} failed: ${e.message}`);
        status = `failed: ${e.message}`;
      }
    } else {
      console.log(`🧪 Dry-run for ${asset}: would initiate flash loan of 1000 ${asset}`);
    }
    assetResults.push({ asset, status });
  }

  // --- Add to report ---
  report.push({
    scenarioFile: file,
    governanceStatus,
    overlayTier,
    expectedRate,
    maxOracleDelay,
    primaryWallet,
    fallbackWallet,
    assets: assetResults
  });
}

async function main() {
  // --- Load token config ---
  let tokenConfig = {};
  try {
    tokenConfig = JSON.parse(fs.readFileSync('hardhat/configs/tokens.json', 'utf8'));
    console.log('📂 Loaded token config:', Object.keys(tokenConfig).join(', '));
  } catch (e) {
    console.log('⚠️ No token config found, proceeding with defaults.');
  }

  // --- Load all scenario files ---
  const scenarioDir = 'hardhat/configs';
  const scenarioFiles = fs.readdirSync(scenarioDir).filter(f => f.startsWith('scenario') && f.endsWith('.json'));
  if (scenarioFiles.length === 0) throw new Error('❌ No scenario files found in hardhat/configs');
  const report = [];
  for (const file of scenarioFiles) {
    await runScenario(`${scenarioDir}/${file}`, tokenConfig, report);
  }

  // --- Save report ---
  fs.writeFileSync('storage/app/scenarioReport.json', JSON.stringify(report, null, 2));
  console.log('\n✅ All scenarios complete. Report saved to scenarioReport.json');

  // --- Console summary ---
  console.log('\n📊 Scenario Summary:');
  report.forEach(r => {
    console.log(`Scenario: ${r.scenarioFile}`);
    console.log(` Governance: ${r.governanceStatus}`);
    r.assets.forEach(a => console.log(`  Asset ${a.asset}: ${a.status}`));
  });

  // --- Dashboard generation ---
  console.log('\n📈 Generating visual dashboard...');
  // Dashboard will be generated by Python script separately
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});